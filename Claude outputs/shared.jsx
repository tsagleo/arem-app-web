const LangContext = createContext({ lang: "fr", setLang: () => {}, t: (k) => k });

export function LangProvider({ children }) {
  const [lang, setLang] = useState(() => localStorage.getItem("app_lang") || "fr");
  function changeLang(l) {
    setLang(l);
    try { localStorage.setItem("app_lang", l); } catch (e) { /* stockage indisponible, ignorer */ }
  }
  const t = (key) => DICTIONARY[lang]?.[key] || DICTIONARY.fr[key] || key;
  return <LangContext.Provider value={{ lang, setLang: changeLang, t }}>{children}</LangContext.Provider>;
}
export function useLang() { return useContext(LangContext); }

export function LanguageSwitcher() {
  const { lang, setLang } = useLang();
  return (
    <select value={lang} onChange={(e) => setLang(e.target.value)} style={{
      background: "rgba(255,255,255,.1)", color: "white", border: "1px solid rgba(255,255,255,.3)",
      borderRadius: 6, fontSize: 11.5, padding: "3px 6px",
    }}>
      <option value="fr" style={{ color: "black" }}>FR</option>
      <option value="en" style={{ color: "black" }}>EN</option>
    </select>
  );
}

