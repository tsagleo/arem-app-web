export function money(n, devise = "CAD") {
  const v = Number(n) || 0;
  const sign = v < 0 ? "-" : "";
  return `${sign}${Math.abs(v).toLocaleString("fr-CA", { minimumFractionDigits: 2, maximumFractionDigits: 2 })} ${devise}`;
}
