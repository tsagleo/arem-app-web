// Bloc de signature saisissable pour les documents imprimables/téléchargeables
// (procès-verbal d'élection, reçu de don, etc.) : le nom du signataire se
// tape dans un champ, puis "Valider" le fige en texte propre pour l'impression
// — combiné à la mention "signé électroniquement" affichée au-dessus par l'appelant.
// `printClass` doit correspondre à la classe "no-print" du document appelant
// (ex. "pv-no-print", "don-no-print") pour que les contrôles n'apparaissent pas à l'impression.
export function SignatureLine({ label, t, printClass = "" }) {
  const [name, setName] = useState("");
  const [validated, setValidated] = useState(false);
  const [focused, setFocused] = useState(false);
  return (
    <div style={{ minWidth: 240 }}>
      <div style={{ fontSize: 12, color: "#5B6270", marginBottom: 4 }}>{t("gov_pv_name_label")} :</div>
      <div style={{ display: "flex", alignItems: "center", gap: 8, marginBottom: 24, minHeight: 32 }}>
        {validated ? (
          <>
            <b style={{ fontSize: 13, color: "#222" }}>{name}</b>
            <button type="button" onClick={() => setValidated(false)} className={printClass} style={{ background: "none", border: "none", color: "var(--primary)", cursor: "pointer", fontSize: 11, textDecoration: "underline", padding: 0 }}>
              {t("action_edit")}
            </button>
          </>
        ) : (
          <>
            <input
              type="text"
              value={name}
              onChange={(e) => setName(e.target.value)}
              onFocus={() => setFocused(true)}
              onBlur={() => setFocused(false)}
              placeholder={t("don_receipt_sign_placeholder")}
              style={{
                border: "none", borderBottom: `1.5px solid ${focused ? "var(--primary)" : "#333"}`,
                outline: "none", fontSize: 13, padding: "6px 6px", background: focused ? "#F0F4F8" : "transparent",
                borderRadius: "3px 3px 0 0", flex: 1, minWidth: 140, fontFamily: "inherit", boxSizing: "border-box",
              }}
            />
            <button
              type="button" onClick={() => name.trim() && setValidated(true)} disabled={!name.trim()} className={printClass}
              style={{ fontSize: 10.5, padding: "4px 10px", borderRadius: 999, border: "1px solid var(--primary)", color: "var(--primary)", background: "none", cursor: name.trim() ? "pointer" : "not-allowed", opacity: name.trim() ? 1 : 0.5, flexShrink: 0 }}
            >
              {t("action_validate")}
            </button>
          </>
        )}
      </div>
      <div style={{ borderTop: "1px solid #333", paddingTop: 6, fontSize: 12, fontWeight: 600 }}>{label}</div>
    </div>
  );
}
export function Btn({ children, onClick, variant = "primary", disabled, type = "button", style }) {
  const base = { display: "inline-flex", alignItems: "center", gap: 8, padding: "10px 18px", borderRadius: 999, fontWeight: 600, fontSize: 14, cursor: disabled ? "not-allowed" : "pointer", border: "none", opacity: disabled ? 0.6 : 1 };
  const variants = {
    primary: { background: "var(--accent)", color: "var(--primary-dark)" },
    outline: { background: "transparent", color: "var(--primary)", border: "2px solid var(--primary)" },
    outlineWhite: { background: "transparent", color: "white", border: "2px solid rgba(255,255,255,.6)" },
    danger: { background: RED, color: "white" },
  };
  return <button type={type} onClick={disabled ? undefined : onClick} style={{ ...base, ...variants[variant], ...style }}>{children}</button>;
}
