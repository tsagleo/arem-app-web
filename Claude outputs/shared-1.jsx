// Traduit une erreur Supabase/Postgres/PostgREST technique en un message
// compréhensible pour un humain, plutôt que d'afficher le texte brut renvoyé
// par la base (ex. « duplicate key value violates unique constraint... »).
// Généralisé à toute l'application (2026-09-21) à partir du modèle déjà en
// place dans Funeraire.jsx (suite 70) — demande directe de l'utilisateur
// ("les messages d'erreur [doivent être] lisibles par des humains").
// Usage : friendlyError(error, t) où `t` vient de useLang(). Le détail
// technique original reste visible (console.error côté appelant, et en
// petit texte ici) pour le diagnostic, sans être ce que l'utilisateur voit
// en premier.
export function friendlyError(error, t) {
  if (!error) return t("err_generic");
  const msg = error.message || "";
  // Erreur de schéma PostgREST (ex. "Could not find the 'telephone' column
  // of 'members' in the schema cache") : signifie qu'une migration SQL
  // attendue n'a pas encore été exécutée sur la base — pas une erreur de
  // saisie de l'utilisateur, donc message dédié plutôt que le générique.
  if (error.code === "PGRST204" || error.code === "PGRST205" || /schema cache/i.test(msg)) {
    return t("err_schema_pending");
  }
  if (!navigator?.onLine || /Failed to fetch|NetworkError|network error/i.test(msg)) {
    return t("err_network");
  }
  switch (error.code) {
    case "23505": return t("err_duplicate");
    case "23503": return t("err_foreign_key");
    case "23502": return t("err_missing_value");
    case "23514": return t("err_invalid_value");
    case "42501": return t("err_permission");
    default: return t("err_generic") + (msg ? ` ${t("err_technical_detail")} ${msg}` : "");
  }
}

